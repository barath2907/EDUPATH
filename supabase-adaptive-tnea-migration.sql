-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Dataset Versioning & Tracking Table
-- ─────────────────────────────────────────────────────────────────────────────
create table if not exists public.tnea_dataset_versions (
  id                  bigint generated by default as identity primary key,
  version_code        text not null unique,
  admission_year      integer not null check (admission_year between 2000 and 2100),
  source_authority    text not null default 'Directorate of Technical Education (DTE), Tamil Nadu',
  source_url          text not null,
  source_document     text not null,
  total_colleges      integer not null default 0,
  total_branches      integer not null default 0,
  total_cutoffs       integer not null default 0,
  validation_status   text not null default 'staged' check (
    validation_status in ('staged', 'validated', 'promoted', 'quarantined', 'archived')
  ),
  is_active_production boolean not null default false,
  imported_by         text not null default 'admin',
  imported_at         timestamptz not null default now(),
  promoted_at         timestamptz,
  notes               text
);

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Cutoff Trend Summaries Table
-- Precomputed multi-year trend analytics for fast querying
-- ─────────────────────────────────────────────────────────────────────────────
create table if not exists public.tnea_cutoff_trends (
  id                  bigint generated by default as identity primary key,
  college_code        text not null,
  college_name        text not null,
  branch_code         text not null,
  branch_name         text not null,
  community           text not null check (community in ('OC', 'BC', 'BCM', 'MBC', 'MBC/DNC', 'SC', 'SCA', 'ST')),
  earliest_year       integer not null,
  latest_year         integer not null,
  baseline_cutoff     numeric(5, 2) not null,
  latest_cutoff       numeric(5, 2) not null,
  absolute_change     numeric(5, 2) not null,
  percentage_change   numeric(5, 2) not null,
  volatility          numeric(5, 2) not null,
  direction           text not null check (
    direction in ('Surging', 'Increasing', 'Stable', 'Decreasing', 'Softening')
  ),
  reliability         text not null check (
    reliability in (
      'High Reliability (3+ Years Official Data)',
      'Moderate Reliability (2 Years Official Data)',
      'Limited Data (Single Year Observation)'
    )
  ),
  year_wise_data      jsonb not null default '[]'::jsonb,
  explanation         text not null,
  dataset_version     text not null,
  computed_at         timestamptz not null default now(),
  constraint uq_trend_entity unique (college_code, branch_code, community, dataset_version)
);

create index if not exists idx_tnea_trends_college on public.tnea_cutoff_trends(college_code);
create index if not exists idx_tnea_trends_branch on public.tnea_cutoff_trends(branch_code);
create index if not exists idx_tnea_trends_community on public.tnea_cutoff_trends(community);

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. Model Governance & Version Registry
-- Stores baseline and candidate ML models with evaluation metrics
-- ─────────────────────────────────────────────────────────────────────────────
create table if not exists public.tnea_model_versions (
  id                  bigint generated by default as identity primary key,
  version_id          text not null unique,
  model_name          text not null,
  status              text not null check (status in ('production', 'candidate', 'archived', 'rejected')),
  dataset_version     text not null,
  rf_weight           numeric(4, 3) not null default 0.400,
  xgb_weight          numeric(4, 3) not null default 0.600,
  trend_weight        numeric(4, 3) not null default 0.000,
  mae                 numeric(5, 3) not null,
  rmse                numeric(5, 3) not null,
  r2                  numeric(5, 4) not null,
  accuracy_score      numeric(5, 2) not null,
  drift_psi           numeric(6, 4) not null default 0.0000,
  drift_status        text not null default 'Stable (PSI < 0.1)',
  trained_at          timestamptz not null default now(),
  deployed_at         timestamptz,
  promoted_by         text,
  notes               text
);

-- ─────────────────────────────────────────────────────────────────────────────
-- 4. Drift Detection Records Table
-- ─────────────────────────────────────────────────────────────────────────────
create table if not exists public.tnea_drift_metrics (
  id                  bigint generated by default as identity primary key,
  evaluation_date     date not null default current_date,
  model_version_id    text not null references public.tnea_model_versions(version_id) on delete cascade,
  psi_score           numeric(6, 4) not null,
  drift_classification text not null check (
    drift_classification in ('Stable (PSI < 0.1)', 'Moderate Drift (0.1 <= PSI < 0.25)', 'Significant Drift (PSI >= 0.25)')
  ),
  baseline_samples    integer not null,
  evaluated_samples   integer not null,
  distribution_shift  jsonb not null default '{}'::jsonb,
  action_taken        text not null default 'Logged',
  created_at          timestamptz not null default now()
);

-- ─────────────────────────────────────────────────────────────────────────────
-- 5. Adaptive Pipeline Jobs & Background Queue
-- ─────────────────────────────────────────────────────────────────────────────
create table if not exists public.tnea_adaptive_pipeline_jobs (
  id                  bigint generated by default as identity primary key,
  job_id              text not null unique,
  batch_id            bigint not null,
  filename            text not null,
  source_year         integer not null,
  status              text not null check (
    status in ('queued', 'validating', 'analyzing', 'evaluating_model', 'completed', 'failed', 'rolled_back')
  ),
  started_at          timestamptz not null default now(),
  completed_at        timestamptz,
  step_logs           jsonb not null default '[]'::jsonb,
  validation_summary  jsonb not null default '{}'::jsonb,
  trend_summary       jsonb not null default '{}'::jsonb,
  model_summary       jsonb not null default '{}'::jsonb,
  errors              text[] default array[]::text[]
);

-- ─────────────────────────────────────────────────────────────────────────────
-- 6. Recommendation Refresh Snapshots Table
-- ─────────────────────────────────────────────────────────────────────────────
create table if not exists public.tnea_recommendation_snapshots (
  id                  bigint generated by default as identity primary key,
  student_id          uuid references auth.users(id) on delete cascade,
  student_cutoff      numeric(5, 2) not null,
  community           text not null,
  category_breakdown  jsonb not null default '{}'::jsonb,
  model_version       text not null,
  refreshed_at        timestamptz not null default now()
);

-- ─────────────────────────────────────────────────────────────────────────────
-- 7. Audit Logs Table
-- ─────────────────────────────────────────────────────────────────────────────
create table if not exists public.tnea_pipeline_audit_logs (
  id                  bigint generated by default as identity primary key,
  action              text not null,
  entity_type         text not null,
  entity_id           text not null,
  performed_by        text not null,
  metadata            jsonb not null default '{}'::jsonb,
  created_at          timestamptz not null default now()
);

