-- Copy any original v2 records into v3 without claiming that they are
-- verified. The legacy tables remain available for audit and rollback.
do $$
begin
  if to_regclass('public.tnea_colleges_legacy_v2') is not null then
    insert into tnea_colleges (
      college_code, college_name, location, district, college_type,
      established, naac_grade, nba_accredited, active,
      college_status, verification_status
    )
    select
      college_code, college_name, location, district, college_type,
      established, naac_grade, nba_accredited, active,
      case when active then 'active' else 'inactive' end,
      'pending'
    from tnea_colleges_legacy_v2
    on conflict (college_code) do nothing;

    insert into tnea_branches (
      branch_code, branch_name, active, verification_status
    )
    select
      branch_code, min(branch_name), bool_or(active), 'pending'
    from tnea_branches_legacy_v2
    group by branch_code
    on conflict (branch_code) do nothing;

    insert into tnea_college_branches (
      college_id, branch_id, annual_fees, total_seats, active,
      source_year, verification_status
    )
    select
      new_college.id,
      new_branch.id,
      legacy_branch.annual_fees,
      legacy_branch.total_seats,
      legacy_branch.active,
      null,
      'pending'
    from tnea_branches_legacy_v2 legacy_branch
    join tnea_colleges_legacy_v2 legacy_college
      on legacy_college.id = legacy_branch.college_id
    join tnea_colleges new_college
      on new_college.college_code = legacy_college.college_code
    join tnea_branches new_branch
      on new_branch.branch_code = legacy_branch.branch_code
    where not exists (
      select 1
      from tnea_college_branches existing
      where existing.college_id = new_college.id
        and existing.branch_id = new_branch.id
        and existing.source_year is null
    );

    insert into tnea_cutoffs (
      college_branch_id, year, round, community, cutoff_mark,
      verification_status
    )
    select
      new_college_branch.id,
      legacy_cutoff.year,
      legacy_cutoff.round::text,
      legacy_cutoff.category,
      legacy_cutoff.cutoff,
      'pending'
    from tnea_cutoffs_legacy_v2 legacy_cutoff
    join tnea_branches_legacy_v2 legacy_branch
      on legacy_branch.id = legacy_cutoff.branch_id
    join tnea_colleges_legacy_v2 legacy_college
      on legacy_college.id = legacy_branch.college_id
    join tnea_colleges new_college
      on new_college.college_code = legacy_college.college_code
    join tnea_branches new_branch
      on new_branch.branch_code = legacy_branch.branch_code
    join tnea_college_branches new_college_branch
      on new_college_branch.college_id = new_college.id
      and new_college_branch.branch_id = new_branch.id
      and new_college_branch.source_year is null
    on conflict (
      college_branch_id, year, round, community, allotment_category
    ) do nothing;
  end if;
end
$$;

