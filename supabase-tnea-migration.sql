-- Existing frontend compatibility view. Values remain NULL when unavailable;
-- the view never manufactures fees, seats, cutoffs, or accreditation.
create or replace view tnea_cutoff_view as
select
  c.id                    as cutoff_id,
  c.cutoff_mark           as cutoff,
  c.year,
  c.community             as category,
  c.round,
  b.id                    as branch_id,
  b.branch_code,
  b.branch_name,
  cb.annual_fees,
  cb.total_seats,
  col.id                  as college_id,
  col.college_code,
  col.college_name,
  col.district,
  col.college_type,
  coalesce(col.location, col.city) as location,
  col.naac_grade,
  coalesce(col.nba_accredited, false) as nba_accredited
from tnea_cutoffs c
join tnea_college_branches cb on cb.id = c.college_branch_id
join tnea_branches b on b.id = cb.branch_id
join tnea_colleges col on col.id = cb.college_id
where col.active = true
  and cb.active = true
  and b.active = true
  and c.verification_status = 'verified'
  and cb.verification_status = 'verified'
  and b.verification_status = 'verified'
  and col.verification_status = 'verified';

