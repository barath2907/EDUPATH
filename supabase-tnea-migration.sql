-- PostgreSQL has no CREATE POLICY IF NOT EXISTS. Dropping only the named
-- policy definitions makes this migration safely rerunnable without touching
-- table data.
do $$
declare
  policy_record record;
begin
  for policy_record in
    select *
    from (values
      ('tnea_data_sources', 'verified_sources_are_readable'),
      ('tnea_data_sources', 'admins_manage_sources'),
      ('tnea_import_batches', 'admins_manage_import_batches'),
      ('tnea_colleges', 'verified_colleges_are_readable'),
      ('tnea_colleges', 'admins_manage_colleges'),
      ('tnea_branches', 'verified_branches_are_readable'),
      ('tnea_branches', 'admins_manage_branches'),
      ('tnea_college_branches', 'verified_college_branches_are_readable'),
      ('tnea_college_branches', 'admins_manage_college_branches'),
      ('tnea_categories', 'verified_categories_are_readable'),
      ('tnea_categories', 'admins_manage_categories'),
      ('tnea_counselling_rounds', 'verified_rounds_are_readable'),
      ('tnea_counselling_rounds', 'admins_manage_rounds'),
      ('tnea_cutoffs', 'verified_cutoffs_are_readable'),
      ('tnea_cutoffs', 'admins_manage_cutoffs'),
      ('tnea_ranks', 'verified_ranks_are_readable'),
      ('tnea_ranks', 'admins_manage_ranks'),
      ('tnea_seat_matrix', 'verified_seats_are_readable'),
      ('tnea_seat_matrix', 'admins_manage_seats'),
      ('tnea_vacancies', 'verified_vacancies_are_readable'),
      ('tnea_vacancies', 'admins_manage_vacancies'),
      ('tnea_reservations', 'verified_reservations_are_readable'),
      ('tnea_reservations', 'admins_manage_reservations'),
      ('tnea_counselling_rules', 'verified_rules_are_readable'),
      ('tnea_counselling_rules', 'admins_manage_rules'),
      ('tnea_documents', 'verified_documents_are_readable'),
      ('tnea_documents', 'admins_manage_documents'),
      ('data_sync_status', 'sync_status_is_readable'),
      ('data_sync_status', 'admins_manage_sync_status')
    ) as policies(table_name, policy_name)
  loop
    execute format(
      'drop policy if exists %I on %I',
      policy_record.policy_name,
      policy_record.table_name
    );
  end loop;
end
$$;

