create table if not exists tnea_data_sources (
  id                  bigint generated by default as identity primary key,
  source_name         text not null,
  source_authority    text not null,
  source_url          text not null,
  source_document     text,
  source_year         integer check (source_year between 1990 and 2100),
  source_type         text not null check (
    source_type in (
      'official_portal', 'official_pdf', 'official_csv', 'official_xlsx',
      'government_document', 'third_party'
    )
  ),
  retrieved_at        timestamptz not null default now(),
  effective_date      date,
  data_version        text not null,
  checksum_sha256     text,
  verification_status text not null default 'pending' check (
    verification_status in ('pending', 'verified', 'rejected', 'superseded')
  ),
  verification_notes  text,
  verified_by         uuid references auth.users(id),
  verified_at         timestamptz,
  created_at          timestamptz not null default now(),
  unique (source_url, data_version)
);

