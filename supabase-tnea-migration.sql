-- ============================================================================
-- EduPath — Centralized TNEA Intelligence Schema (v3)
-- PostgreSQL / Supabase
--
-- This migration is intentionally non-destructive: it never drops TNEA data.
-- Run after supabase-migration.sql in Supabase Dashboard -> SQL Editor.
-- Import records as "pending", validate them, then mark them "verified".
-- ============================================================================

create extension if not exists "pgcrypto";

-- Administrative access is derived from immutable auth app_metadata, never from
-- a client-editable profile field.
create or replace function public.is_tnea_admin()
returns boolean
language sql
stable
as $$
  select coalesce(
    (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
    or (auth.jwt() -> 'app_metadata' -> 'roles') ? 'admin',
    false
  );
$$;

-- --------------------------------------------------------------------------
-- One-time, data-preserving upgrade from the original v2 schema
-- --------------------------------------------------------------------------
-- v2 stored college_id directly on tnea_branches. If that shape is found, its
-- tables are retained under *_legacy_v2, then copied into the normalized v3
-- tables below as pending/unverified data. A previous failed v3 run may have
-- created empty dependent tables; those empty shells are removed first.
do $$
declare
  candidate_table text;
  row_found boolean;
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'tnea_branches'
      and column_name = 'college_id'
  ) then
    foreach candidate_table in array array[
      'tnea_vacancies',
      'tnea_seat_matrix',
      'tnea_ranks',
      'tnea_reservations',
      'tnea_counselling_rules',
      'tnea_documents',
      'tnea_categories',
      'tnea_counselling_rounds',
      'data_sync_status',
      'tnea_college_branches'
    ]
    loop
      if to_regclass('public.' || candidate_table) is not null then
        execute format('select exists (select 1 from %I limit 1)', candidate_table)
          into row_found;
        if row_found then
          raise exception
            'Cannot automatically upgrade: partial v3 table "%" contains data.',
            candidate_table;
        end if;
        execute format('drop table %I cascade', candidate_table);
      end if;
    end loop;

    if to_regclass('public.tnea_cutoff_view') is not null then
      alter view tnea_cutoff_view rename to tnea_cutoff_view_legacy_v2;
    end if;
    alter table tnea_cutoffs rename to tnea_cutoffs_legacy_v2;
    alter table tnea_branches rename to tnea_branches_legacy_v2;
    alter table tnea_colleges rename to tnea_colleges_legacy_v2;
    alter table tnea_import_batches rename to tnea_import_batches_legacy_v2;
  end if;
end
$$;

